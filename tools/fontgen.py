"""Generate LVGL 8 bitmap fonts (4 bpp) from TTF files with Pillow.

A tiny replacement for lv_font_conv (no Node.js needed). Run from the repo root:
    python tools/fontgen.py
Writes firmware/src/fonts/*.c and firmware/src/fonts/fonts.h
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = Path(__file__).resolve().parent / "fonts"
OUT = ROOT / "firmware" / "src" / "fonts"
B612R = FONTS / "B612Mono-Regular.ttf"   # Airbus cockpit font (OFL)
B612B = FONTS / "B612Mono-Bold.ttf"
ICONS = FONTS / "MaterialIcons-Regular.ttf"

LATIN1 = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + [0x2192, 0x2022]  # + → •
DIGITS = [ord(c) for c in " 0123456789:%-.°"]

# Material Icons we use (name -> codepoint); names become ICON_* macros
ICON_SET = {
    "PLAY": 0xE037, "PAUSE": 0xE034, "NEXT": 0xE044, "PREV": 0xE045,
    "VOL": 0xE050, "MUTE": 0xE04F, "MINUS": 0xE15B, "PLUS": 0xE145,
    "WIFI": 0xE63E, "WIFI_OFF": 0xE648, "MUSIC": 0xE405, "BRIGHT": 0xE3AB,
    "SUN": 0xE430, "MOON": 0xEA46, "CLOUD": 0xE2BD, "PARTLY": 0xE42D,
    "FOG": 0xE818, "DRIZZLE": 0xE3EA, "RAIN": 0xE798, "SNOW": 0xEB3B,
    "STORM": 0xEBDB, "UPDATE": 0xE62A, "PC": 0xE30C, "PIN": 0xE0C8, "SLEEP": 0xEF44,
}

# (c name, ttf, px, weight, charset, fallback)
SPECS = [
    ("font_tiny", B612B, 9, None, LATIN1, None),
    ("font_cap", B612B, 11, None, LATIN1, None),
    ("font_small", B612R, 12, None, LATIN1, "icons_16"),
    ("font_body", B612B, 14, None, LATIN1, "icons_16"),
    ("font_value", B612B, 18, None, LATIN1, "icons_24"),
    ("font_num", B612B, 26, None, DIGITS, None),
    ("icons_16", ICONS, 16, None, sorted(ICON_SET.values()), None),
    ("icons_24", ICONS, 24, None, sorted(ICON_SET.values()), None),
    ("icons_32", ICONS, 32, None, sorted(ICON_SET.values()), None),
]


def load(ttf: Path, px: int, weight: int | None) -> ImageFont.FreeTypeFont:
    f = ImageFont.truetype(str(ttf), px)
    if weight is not None:
        axes = {a["name"]: a for a in f.get_variation_axes()}
        vals = []
        for name, a in axes.items():
            n = name.decode() if isinstance(name, bytes) else name
            if n.lower().startswith("weight") or n == "wght":
                vals.append(weight)
            elif n.lower().startswith("optical") or n == "opsz":
                vals.append(max(a["minimum"], min(a["maximum"], px)))
            else:
                vals.append(a["default"])
        f.set_variation_by_axes(vals)
    return f


def pack4(pixels: list[int]) -> list[int]:
    nib = [p >> 4 for p in pixels]
    if len(nib) % 2:
        nib.append(0)
    return [(nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2)]


def gen(name: str, ttf: Path, px: int, weight, charset, fallback) -> None:
    f = load(ttf, px, weight)
    ascent, descent = f.getmetrics()
    bitmap: list[int] = []
    dsc = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0}"]
    cps = []
    for cp in sorted(set(charset)):
        ch = chr(cp)
        adv = round(f.getlength(ch) * 16)
        l, t, r, b = f.getbbox(ch)
        w, h = max(0, r - l), max(0, b - t)
        if ttf == ICONS and w == 0:
            raise SystemExit(f"icon U+{cp:04X} missing from font")
        idx = len(bitmap)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255)
            bitmap += pack4(list(im.tobytes()))
        dsc.append(f"    {{.bitmap_index = {idx}, .adv_w = {adv}, .box_w = {w}, .box_h = {h}, "
                   f".ofs_x = {l}, .ofs_y = {ascent - b}}}")
        cps.append(cp)

    first = cps[0]
    offsets = [cp - first for cp in cps]
    rows = [", ".join(f"0x{v:02x}" for v in bitmap[i:i + 24]) for i in range(0, len(bitmap), 24)]
    fb = f"&{fallback}" if fallback else "NULL"
    ext = f"extern const lv_font_t {fallback};\n" if fallback else ""
    src = f"""// Generated by tools/fontgen.py from {ttf.name} ({px}px{f', wght {weight}' if weight else ''}) - do not edit
#include "lvgl.h"
{ext}
static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {{
    {(',' + chr(10) + '    ').join(rows) or '0'}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{(',' + chr(10)).join(dsc)}
}};

static const uint16_t unicode_list[] = {{
    {', '.join(f'0x{o:x}' for o in offsets)}
}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{.range_start = {first}, .range_length = {offsets[-1] + 1}, .glyph_id_start = 1,
     .unicode_list = unicode_list, .glyph_id_ofs_list = NULL, .list_length = {len(cps)},
     .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}
}};

static lv_font_fmt_txt_glyph_cache_t cache;

static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = 1,
    .bpp = 4,
    .kern_classes = 0,
    .bitmap_format = 0,
    .cache = &cache,
}};

const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent},
    .base_line = {descent},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -1,
    .underline_thickness = 1,
    .dsc = &font_dsc,
    .fallback = {fb},
    .user_data = NULL,
}};
"""
    (OUT / f"{name}.c").write_text(src, encoding="utf-8")
    print(f"{name:12s} {len(cps):4d} glyphs  {len(bitmap) / 1024:6.1f} KB")


def utf8_escape(cp: int) -> str:
    return "".join(f"\\x{b:02X}" for b in chr(cp).encode())


SOURCES = {  # both fonts are open source (OFL / Apache 2.0)
    B612R: "https://raw.githubusercontent.com/google/fonts/main/ofl/b612mono/B612Mono-Regular.ttf",
    B612B: "https://raw.githubusercontent.com/google/fonts/main/ofl/b612mono/B612Mono-Bold.ttf",
    ICONS: "https://raw.githubusercontent.com/google/material-design-icons/master/font/"
           "MaterialIcons-Regular.ttf",
}


def fetch_fonts() -> None:
    import urllib.request
    FONTS.mkdir(exist_ok=True)
    for path, url in SOURCES.items():
        if not path.exists():
            print("downloading", path.name)
            urllib.request.urlretrieve(url, path)


def main() -> None:
    fetch_fonts()
    OUT.mkdir(parents=True, exist_ok=True)
    for spec in SPECS:
        gen(*spec)
    lines = ["// Generated by tools/fontgen.py - do not edit", "#pragma once", '#include "lvgl.h"', ""]
    lines += [f"extern const lv_font_t {s[0]};" for s in SPECS]
    lines.append("")
    lines += [f'#define ICON_{k} "{utf8_escape(v)}"' for k, v in ICON_SET.items()]
    (OUT / "fonts.h").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
